// 🔴 ここは**人が書いて人が直す場所**。自動生成しない（測っていないことを断定させないため）。
// 🔵 数値の現状（株価・トレンド・相対力）は `poirobo_stocks.json` が毎営業日入れ替える。
//    この文章は状況が変わったときだけ手で直す。
//
// 🔴 **枠の意味（2026-08-16 の相談で決めた）**
//    仮説が2つに割れているので、**どちらの層に賭けているかを枠ごとにラベルする**。
//    A案＝工場の自動化が桁を変える（中心はロボット・工作機械の本体メーカー）
//    B案＝人型・汎用ロボが普及する（中心は関節・減速機・ベアリングの部品メーカー）
//    こう記録しておくと、後から「**どちらの層に価値が落ちたか**」を答え合わせできる。
//
// 🔴 **選ぶ基準はひとつ＝独占があるか**（2026-08-16 の相談で確定）。
//    独占（代替の効かなさ）が無ければ、台数が増えても値下げ競争で終わる。
//    キオクシアが桁で動いたのも、突き詰めればNANDが5〜6社の寡占だったから。
//    🔵 安川電機を枠から外したのは、値動きがファナックと被る以上に**サーボの独占が薄い**（中国Inovanceが首位）ため。

export type Lane = 'A' | 'B' | 'AB' | 'C'

export type Thesis = {
  code: string
  /** どの仮説に賭けている枠か */
  lane: Lane
  /** 枠の説明（画面のチップに出る短文） */
  laneLabel: string
  /** 一言で言うと。画面のいちばん大きい文字になる */
  headline: string
  /**
   * 🔴 **選定基準の中核＝独占（代替の効かなさ）**（2026-08-16 の相談で確定）。
   *    独占が無いと、台数が増えても値下げ競争で終わる。独占があると、需要増がそのまま利益になる。
   */
  moat: { label: string; detail: string }
  /** なぜ見ているか（仮説・箇条書き） */
  why: string[]
  /** 効いていれば出てくるはずの数字（＝答え合わせの材料） */
  confirm: string[]
  /** この見立てが崩れる条件 */
  breaks: string[]
  /** 決算の出方（🔴 日付は会社発表で確定。ここは「例年の時期」） */
  earnings: string
  /** 観測を始めた日（＝ここから先の成績を測る起点） */
  markedOn: string
  /** 見立てを最後に見直した日 */
  reviewed: string
}

